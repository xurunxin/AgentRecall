export type ConflictPolicy = "keep" | "replace" | "merge" | "fail";

export type ImportHistoryMode = "snapshot" | "full_history";

export type ImportSensitivityPolicy = "normal" | "private" | "restricted";

/**
 * Preflight errors. A preflight failure is a
 * contract-level rejection of the bundle, distinct
 * from a per-entry write error. The preflight phase
 * returns a structured `{ ok: false, error, ... }`
 * so the CLI can print the failing entry id +
 * reason without leaking the entry body. The
 * failing entry id (if any) is in `details.entry_id`.
 */
export type PreflightError =
  | "invalid_schema"
  | "invalid_state"
  | "secret_detected"
  | "sensitivity_denied"
  | "identity_conflict"
  | "aggregate_budget"
  | "revision_drift"
  | "bundle_garbled"
  | "unauthorized";

export type PreflightResult = Result<
  {
    bundle: NormalisedBundle;
    import_batch_id: string;
    /**
     * Stage 18 v1.1.2 (issue #24, task 5):
     * deterministic plan: per-entry decisions
     * plus the `before` / `after` budget summary
     * computed from the live budget usage.
     */
    preflight: PreflightPlan;
  },
  PreflightError
>;

/**
 * Stage 18 v1.1.2 (issue #24, task 5): the
 * deterministic preflight surface. The plan is
 * inspectable and reproducible: the same bundle
 * + the same live store produce the same plan
 * (the `before` usage is sampled from the
 * store at preflight time; the `after` is
 * computed by `projectBatchBudget`). The plan
 * is also the audit surface for the preflight
 * (`audit_events` can record the
 * `before` / `after` summary so a reviewer
 * later knows what the live budget looked
 * like at preflight time).
 */
export type PreflightPlanDecision =
  | { kind: "insert"; memory_id: string }
  | { kind: "replace"; memory_id: string; existing_id: string }
  | { kind: "merge"; memory_id: string; existing_id: string }
  | { kind: "skip"; memory_id: string; reason: string }
  | { kind: "reject"; memory_id: string; reason: string };

export type PreflightPlan = {
  /**
   * Per-entry decision, in import order. The
   * preflight attaches a `reject` decision when
   * AND only when the entry was the failing one
   * (the preflight is fail-fast: the first
   * failing entry's decision is `reject`, every
   * earlier entry's decision is `insert` /
   * `replace` / `merge` / `skip`). The CLI can
   * surface the `before` budget summary even
   * on a failed preflight.
   */
  decisions: PreflightPlanDecision[];
  budget: {
    /** The live budget usage captured at preflight time. */
    before: BudgetUsage;
    /** The projected budget after the batch (when all ops succeed). */
    after: BudgetUsage;
    /** The configured budget limits (project / global). */
    active_budget: MemoryBudget;
    /** Net change to `active_chars` (`batch_chars - releases`). */
    batch_chars: number;
    /** Sum of `char_count` released by replaces / merges. */
    releases: number;
    /** Net change to `active_chars`. */
    net_chars: number;
    /** Net change to `index_chars`. */
    net_index_chars: number;
    /** Count of inserts / replaces / merges. */
    inserts: number;
    replacements: number;
    merges: number;
  };
};

export type ImportPlan = {
  manifest: Manifest;
  scope: MemoryScope;
  project_id?: string;
  /** Bundle generation after the migration adapter. */
  generation: BundleGeneration;
  /** Stable bundle hash (sha256 of the normalised bundle). */
  bundle_hash: string;
  /** UUID identifying this import run. */
  import_batch_id: string;
  /** `snapshot` or `full_history`. */
  history_mode: ImportHistoryMode;
  /** Entries that will be inserted (no existing id). */
  inserts: MemoryEntry[];
  /** Entries that will be replaced (existing id, conflict policy != keep). */
  replacements: { imported: MemoryEntry; existing: MemoryEntry }[];
  /** Entries that will be skipped under `keep`. */
  skipped: MemoryEntry[];
  /** Per-entry status, in import order. */
  decisions: Array<
    | { kind: "insert"; memory_id: string }
    | { kind: "replace"; memory_id: string }
    | { kind: "merge"; memory_id: string }
    | { kind: "skip"; memory_id: string; reason: string }
  >;
  /**
   * Stage 18 v1.1.2 (issue #24, task 5): the
   * deterministic preflight plan (v1 summary
   * + per-entry decisions). The apply phase
   * uses this to re-validate at apply time.
   */
  preflight?: PreflightPlan;
};

export type ImportOptions = {
  conflict: ConflictPolicy;
  dry_run: boolean;
  actor: string;
  /**
   * When true (the default), abort on a manifest
   * hash mismatch. Stage 15 PR-M0-3 (issue #4, spec
   * § 6.7) flips the default to true — the v1
   * contract made the verification opt-in, which
   * meant an entry could be silently dropped from
   * the export without the import noticing.
   */
  require_clean_manifest?: boolean;
  /**
   * Stage 16 v1.1.1 PR-4 (issue #13). `snapshot`
   * (default) imports the current entry fields
   * only. `full_history` also restores the
   * `memory_revisions` and `audit_events` chain.
   */
  history_mode?: ImportHistoryMode;
  /**
   * Stage 16 v1.1.1 PR-4 (issue #13). The live
   * sensitivity policy. `restricted` entries may
   * not leave the source DB unless the caller
   * passes `allow_restricted: true`.
   */
  allow_restricted?: boolean;
  /**
   * Stage 16 v1.1.1 PR-4 (issue #13). When true,
   * a `full_history` import is allowed to restore
   * a `user_confirmed` trust tier from the bundle.
   * Default `false`. The trusted-bundle mechanism
   * in this release is the explicit
   * `--restore-trust` CLI flag; remote signing
   * infrastructure is explicitly a non-goal.
   *
   * Stage 18 v1.1.2 (issue #23, ADR-0001): the
   * `restore_trust` flag is now gated on a valid
   * `capability` (see below). A bare
   * `restore_trust: true` without a capability is
   * rejected at preflight with `unauthorized`.
   * The flag itself is preserved for backward
   * compatibility; the v1.1.2 contract pins the
   * authorization decision on the
   * `import_trust_restore` capability type.
   */
  restore_trust?: boolean;
  /**
   * Stage 18 v1.1.2 (issue #23, ADR-0001): the
   * operator capability token. Required when the
   * import would re-claim a non-`imported` trust
   * tier (`restore_trust: true` + `full_history`)
   * OR a `sensitivity: "restricted"` row
   * (`allow_restricted: true`). The preflight
   * calls `MemoryService.adminCapabilityStore.authorize(...)`
   * on the matching capability type and rejects
   * the bundle with `unauthorized` when the
   * capability is missing, malformed, or
   * mismatched. The token is NEVER surfaced in
   * the error message; the failure surfaces the
   * stable `unauthorized` reason code.
   */
  capability?: string;
};

